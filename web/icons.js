/** An inline SVG icon. Decorative by default; pass a label when the icon is the only content. */
export function ico(name, cls = '', label = '') {
  const filled = FILLED[name];
  const body = filled ?? P[name];
  if (!body) return '';
  const a11y = label ? `role="img" aria-label="${label}"` : 'aria-hidden="true"';
  return `<svg class="i${filled ? ' i-fill' : ''}${cls ? ` ${cls}` : ''}" viewBox="0 0 24 24" ${a11y}>${body}</svg>`;
}

